#!/usr/bin/env python3
"""Create a throwaway demo vault with entirely fake accounts, for local
development and testing only.

Exercises exactly the KDBX feature set the app depends on (see spec
section: validate pykeepass compatibility first, against a generated
demo vault, never the user's real database):

  - KDBX4 database creation (``pykeepass.create_database``)
  - a generated Key File (no master password -- matches this project's
    chosen "Key File only" configuration, spec section 2)
  - AES-256 encryption, **Argon2id** KDF (pykeepass's own default is
    actually Argon2d; ``create_vault()`` upgrades it in place and this
    script's own validation, plus ``tests/test_vault_kdbx.py``, assert
    the reopened database reports ``kdf_algorithm == "argon2id"`` -- see
    core/vault/kdbx.py's ``_upgrade_kdf_to_argon2id`` for exactly how)
  - custom string attributes (``PM_ServiceName``, ``PM_AppIdentifiers``,
    ``PM_AuthStrategy``, protected ``otp``, protected ``PM_RecoveryCodes``)
  - reading everything back through ``passman.core.vault.kdbx``, the same
    compatibility layer the real application uses -- this script IS the
    validation, not a separate mock.

Every credential below is fake, generated by this script, and used
nowhere else. Never point ``--out`` at a real vault location.
"""

from __future__ import annotations

import argparse
import json
import secrets
import shutil
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "src"))

from passman.core.auth.strategy import DEFAULT_STRATEGY, MULTI_PAGE_STRATEGY  # noqa: E402
from passman.core.security.memory import SecretBytes  # noqa: E402
from passman.core.totp.totp import TotpConfig, normalize_base32_secret  # noqa: E402
from passman.core.vault.kdbx import create_vault, open_vault  # noqa: E402
from passman.core.vault.models import RecoveryCode  # noqa: E402

FAKE_TOTP_SECRET = normalize_base32_secret("JBSWY3DPEHPK3PXP")  # RFC 4648 test vector, not a real secret


def _fake_recovery_codes(n: int = 8) -> list[RecoveryCode]:
    return [RecoveryCode(code=f"demo-{secrets.token_hex(4)}", used=False, label="") for _ in range(n)]


